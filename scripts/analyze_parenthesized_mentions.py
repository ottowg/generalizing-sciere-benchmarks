"""Analyze predicted mentions containing parenthesized abbreviations.

Finds mentions like "Bidirectional Encoder Representations from Transformers ( BERT )"
across all unified predictions on dev sets.
"""

import re
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from typing import Literal

from unifiedsciere.data_loader import load_corpus
from unifiedsciere.unification.pipeline import apply_unification_pipeline

PAREN_PATTERN = re.compile(r"\(.*?\)")

DATASETS: list[Literal["scier", "scinlp", "gsap"]] = ["scier", "scinlp", "gsap"]
MODELS: list[Literal["scier", "scinlp", "gsap"]] = ["scier", "scinlp", "gsap"]
SPLIT: Literal["dev"] = "dev"
MAX_EXAMPLES = 5


def main():
    output_dir = Path("reports/analysis")
    output_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    md = f"""# Parenthesized Mentions Analysis

**Generated:** {timestamp}

**Split:** {SPLIT}

## Overview

This report identifies predicted mentions that contain parenthesized text,
e.g. "Bidirectional Encoder Representations from Transformers ( BERT )".
These often represent full-name-plus-abbreviation patterns in scientific text.

All predictions are evaluated after applying the complete unification pipeline.

"""

    for dataset in DATASETS:
        md += f"## {dataset.upper()} Dataset\n\n"

        for model in MODELS:
            try:
                corpus = load_corpus(
                    dataset, SPLIT, data_type="predictions", trained_on=model
                )
                unified, _ = apply_unification_pipeline(
                    corpus,
                    dataset=model,
                    apply_to_gold=False,
                    apply_to_predicted=True,
                )

                predictions = unified.mentions_predicted

                # Group by entity type
                by_label: dict[str, list] = defaultdict(list)
                total_by_label: dict[str, int] = defaultdict(int)

                for m in predictions:
                    total_by_label[m.label] += 1
                    if PAREN_PATTERN.search(m.text):
                        by_label[m.label].append(m.text)

                md += f"### {model.upper()} Model\n\n"

                if not any(by_label.values()):
                    md += "No parenthesized mentions found.\n\n"
                    md += "---\n\n"
                    continue

                md += "| Entity Type | Count | Total | % | Examples |\n"
                md += "|-------------|-------|-------|---|----------|\n"

                for label in sorted(
                    set(list(by_label.keys()) + list(total_by_label.keys()))
                ):
                    matches = by_label.get(label, [])
                    total = total_by_label.get(label, 0)
                    count = len(matches)
                    pct = (count / total * 100) if total > 0 else 0.0
                    examples = "; ".join(
                        f'"{t}"' for t in matches[:MAX_EXAMPLES]
                    ).replace("|", "\\|")
                    md += f"| {label} | {count} | {total} | {pct:.1f}% | {examples} |\n"

                # Totals row
                total_matches = sum(len(v) for v in by_label.values())
                total_all = sum(total_by_label.values())
                total_pct = (total_matches / total_all * 100) if total_all > 0 else 0.0
                md += f"| **Total** | **{total_matches}** | **{total_all}** | **{total_pct:.1f}%** | |\n"

                md += "\n---\n\n"

            except Exception as e:
                md += f"### {model.upper()} Model\n\n"
                md += f"**Error:** {e}\n\n---\n\n"

    md += """
## Notes

- **Pattern**: Any mention text containing `(...)` is counted
- Tokens are space-joined, so abbreviations appear as `( BERT )` rather than `(BERT)`
- All metrics computed after full unification pipeline (merge, drop, map, dataset-specific corrections)

---
*Generated by UnifiedSciERE Parenthesized Mentions Analysis*
"""

    out_path = output_dir / f"parenthesized_mentions_{SPLIT}.md"
    out_path.write_text(md)
    print(f"Report saved to: {out_path}")


if __name__ == "__main__":
    main()
